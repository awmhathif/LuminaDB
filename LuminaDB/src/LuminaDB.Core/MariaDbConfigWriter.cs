using System;
using System.Globalization;
using System.IO;
using System.Text;

namespace LuminaDB.Core
{
    /// <summary>Inputs for my.ini. Paths must be absolute.</summary>
    public sealed class MariaDbConfig
    {
        public string DataDir { get; set; }
        public int Port { get; set; }
        public string SecureFilePriv { get; set; }
        public string PluginDir { get; set; }
        public string TempDir { get; set; }
        public ulong TotalRamBytes { get; set; }
        public bool SupportsCharacterSetCollations { get; set; }
    }

    /// <summary>
    /// Writes my.ini with the defaults verified in ParityTests/database/RESULTS.md §3.
    /// Generated fresh at every start, so a broken hand edit can never stop the server (SPEC §4).
    /// </summary>
    public static class MariaDbConfigWriter
    {
        public static string Render(MariaDbConfig c)
        {
            if (c == null) throw new ArgumentNullException(nameof(c));
            Require(c.DataDir, nameof(c.DataDir));
            Require(c.SecureFilePriv, nameof(c.SecureFilePriv));
            Require(c.PluginDir, nameof(c.PluginDir));
            Require(c.TempDir, nameof(c.TempDir));
            if (c.Port < 1 || c.Port > 65535) throw new ArgumentOutOfRangeException(nameof(c.Port));

            var sb = new StringBuilder();
            sb.AppendLine("# Generated by LuminaDB at every start. Do not edit: use Settings > Advanced instead.");
            sb.AppendLine("[mysqld]");
            sb.AppendLine("datadir=" + IniPath(c.DataDir));
            sb.AppendLine("port=" + c.Port.ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("bind-address=127.0.0.1");
            sb.AppendLine("tmpdir=" + IniPath(c.TempDir));
            sb.AppendLine("plugin-dir=" + IniPath(c.PluginDir));
            sb.AppendLine("character-set-server=utf8mb4");
            sb.AppendLine("collation-server=utf8mb4_unicode_ci");
            if (c.SupportsCharacterSetCollations)
                sb.AppendLine("character_set_collations=utf8mb4=utf8mb4_unicode_ci,utf8mb3=utf8mb3_unicode_ci");
            sb.AppendLine("event_scheduler=ON");
            sb.AppendLine("local_infile=ON");
            sb.AppendLine("secure_file_priv=\"" + IniPath(c.SecureFilePriv) + "\"");
            sb.AppendLine("max_allowed_packet=256M");
            sb.AppendLine("innodb_buffer_pool_size=" + BufferPoolMb(c.TotalRamBytes).ToString(CultureInfo.InvariantCulture) + "M");
            sb.AppendLine("performance_schema=ON");
            sb.AppendLine("slow_query_log=OFF");
            sb.AppendLine("long_query_time=2");
            sb.AppendLine("log_output=FILE");
            sb.AppendLine("lower_case_table_names=1");
            // skip-name-resolve deliberately NOT set: TCP logins would then match root@127.0.0.1
            // instead of root@localhost (RESULTS.md §3).
            sb.AppendLine();
            sb.AppendLine("[client]");
            sb.AppendLine("port=" + c.Port.ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("default-character-set=utf8mb4");
            sb.AppendLine("plugin-dir=" + IniPath(c.PluginDir));
            sb.AppendLine();
            // local-infile must be under [mysql], NOT [client]: in [client] it breaks the dump tools.
            sb.AppendLine("[mysql]");
            sb.AppendLine("local-infile=1");
            return sb.ToString();
        }

        public static void Write(string path, MariaDbConfig c)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(path));
            var tmp = path + ".tmp";
            File.WriteAllText(tmp, Render(c), new UTF8Encoding(false));
            if (File.Exists(path)) File.Replace(tmp, path, null);
            else File.Move(tmp, path);
        }

        /// <summary>
        /// 256 MB is the verified default; on small PCs keep it to 1/8 of RAM (min 64 MB) so a
        /// 2 GB lab PC still has room for Windows, a browser and PHP.
        /// </summary>
        public static int BufferPoolMb(ulong totalRamBytes)
        {
            if (totalRamBytes == 0) return 128;
            ulong eighth = totalRamBytes / 8 / (1024 * 1024);
            return (int)Math.Max(64, Math.Min(256, eighth));
        }

        /// <summary>MariaDB option files accept forward slashes on Windows and treat backslashes as escapes.</summary>
        internal static string IniPath(string path) => Path.GetFullPath(path).Replace('\\', '/');

        private static void Require(string value, string name)
        {
            if (string.IsNullOrWhiteSpace(value)) throw new ArgumentException(name + " is required.", name);
        }
    }
}
