namespace LuminaDB.Core.Web
{
    /// <summary>One project as the web server sees it.</summary>
    public sealed class SiteInfo
    {
        public string Name { get; set; }
        public string DocumentRoot { get; set; }
        /// <summary>Has an .htaccess: served by Apache behind Caddy (SPEC §5.2).</summary>
        public bool UsesApache { get; set; }
    }

    /// <summary>Temporarily serving one project to the local network (SPEC §5.2 demo mode).</summary>
    public sealed class DemoSite
    {
        public string Project { get; set; }
        public string Address { get; set; }
        public int Port { get; set; }
        public string Url => "http://" + Address + ":" + Port.ToString(CultureInfo.InvariantCulture) + "/";
    }

    /// <summary>Everything the generated web server configs need.</summary>
    public sealed class WebPlan
    {
        public int WebPort { get; set; }
        public int PhpPort { get; set; }
        public int AdminPort { get; set; }
        /// <summary>Apache's internal port when it runs behind Caddy, or 0.</summary>
        public int ApachePort { get; set; }
        /// <summary>True when Apache is the front server (sets without Caddy).</summary>
        public bool ApacheInFront { get; set; }
        public List<SiteInfo> Sites { get; set; } = new List<SiteInfo>();
        public DemoSite Demo { get; set; }
        /// <summary>The phpmyadmin folder when the phpMyAdmin switch is on (SPEC §5.13), else null.</summary>
        public string PhpMyAdminDir { get; set; }

        public bool NeedsApache => ApacheInFront || Sites.Any(s => s.UsesApache);
    }

    /// <summary>
    /// Writes the Caddyfile, httpd.conf and the project index page (SPEC §4 ConfigWriter: generated at every start,
    /// absolute paths, loopback only). Settings proven in ParityTests\web: Caddy needs "bind 127.0.0.1" (without it,
    /// it listens on every interface and starts silently on a busy port); Apache + php-cgi needs the trailing "/" in
    /// SetHandler plus the ProxyFCGISetEnvIf fix for Windows paths.
    /// </summary>
    public static class WebConfig
    {
        public const string DemoHeader = "X-Lumina-Demo";

        public static string CaddyFile(AppPaths p) => Path.Combine(p.Config, "Caddyfile");
        public static string ApacheFile(AppPaths p) => Path.Combine(p.Config, "httpd.conf");
        public static string IndexFolder(AppPaths p) => Path.Combine(p.Config, "lumina", "www");
        public static string CaddyLog(AppPaths p) => Path.Combine(p.Logs, "caddy.log");
        public static string ApacheErrorLog(AppPaths p) => Path.Combine(p.Logs, "apache-error.log");
        public static string AccessLog(AppPaths p, string project) => Path.Combine(p.ProjectLogs, project + "-access.log");
        public static string PhpLog(AppPaths p, string project) => Path.Combine(p.ProjectLogs, project + "-php.log");

        private static string Fwd(string path) => path.Replace('\\', '/');
        private static string Q(string path) => "\"" + Fwd(path) + "\"";
        private static string N(int n) => n.ToString(CultureInfo.InvariantCulture);

        // ------------------------------------------------------------------ Caddy

        public static string BuildCaddyfile(AppPaths paths, WebPlan plan)
        {
            var sb = new StringBuilder();
            sb.AppendLine("# Generated by LuminaDB at every start. Don't edit: it is rewritten next time.");
            sb.AppendLine("{");
            sb.AppendLine("\tadmin 127.0.0.1:" + N(plan.AdminPort));
            sb.AppendLine("\tauto_https off");
            sb.AppendLine("\tpersist_config off");
            sb.AppendLine("\tstorage file_system " + Q(Path.Combine(paths.Run, "caddy")));
            sb.AppendLine("\tskip_install_trust");
            sb.AppendLine("\tgrace_period 3s");
            sb.AppendLine("\tlog {");
            sb.AppendLine("\t\toutput file " + Q(CaddyLog(paths)) + " {");
            sb.AppendLine("\t\t\troll_size 5MiB");
            sb.AppendLine("\t\t\troll_keep 2");
            sb.AppendLine("\t\t}");
            sb.AppendLine("\t\tlevel WARN");
            sb.AppendLine("\t}");
            sb.AppendLine("}");
            sb.AppendLine();
            sb.AppendLine("(lumina_common) {");
            sb.AppendLine("\tbind 127.0.0.1");
            sb.AppendLine("\trequest_header -" + DemoHeader);
            sb.AppendLine("\trequest_body {");
            sb.AppendLine("\t\tmax_size 256MB");
            sb.AppendLine("\t}");
            sb.AppendLine("}");
            sb.AppendLine();

            foreach (var s in plan.Sites)
            {
                sb.AppendLine("http://" + s.Name + ".localhost:" + N(plan.WebPort) + " {");
                sb.AppendLine("\timport lumina_common");
                AppendAccessLog(sb, paths, s.Name, "\t");
                AppendSite(sb, s, plan, "\t", pathPrefix: null);
                sb.AppendLine("}");
                sb.AppendLine();
            }

            if (plan.PhpMyAdminDir != null)
            {
                sb.AppendLine("http://" + PhpMyAdminConfig.Host + ".localhost:" + N(plan.WebPort) + " {");
                sb.AppendLine("\timport lumina_common");
                // phpMyAdmin's code, templates and setup pages are never served directly (ParityTests web/RESULTS).
                sb.AppendLine("\t@lumina_pma_private {");
                sb.AppendLine("\t\tpath_regexp ^/(\\.|libraries/|templates/|vendor/|sql/|setup/|tmp/|config\\.|composer\\.|package\\.json)");
                sb.AppendLine("\t}");
                sb.AppendLine("\trespond @lumina_pma_private \"Hidden by LuminaDB: phpMyAdmin's own files are private.\" 403");
                sb.AppendLine("\troot * " + Q(plan.PhpMyAdminDir));
                sb.AppendLine("\tphp_fastcgi 127.0.0.1:" + N(plan.PhpPort) + " {");
                sb.AppendLine("\t\tlb_try_duration 5s");
                sb.AppendLine("\t}");
                sb.AppendLine("\tfile_server");
                sb.AppendLine("}");
                sb.AppendLine();
            }

            // http://localhost:<port>/ : the index page, plus every project at /<name>/ for browsers without *.localhost.
            sb.AppendLine("http://localhost:" + N(plan.WebPort) + ", http://127.0.0.1:" + N(plan.WebPort) + " {");
            sb.AppendLine("\timport lumina_common");
            if (plan.PhpMyAdminDir != null)
                sb.AppendLine("\tredir /phpmyadmin* http://" + PhpMyAdminConfig.Host + ".localhost:" + N(plan.WebPort) + "/ 302");
            foreach (var s in plan.Sites)
            {
                sb.AppendLine("\tredir /" + s.Name + " /" + s.Name + "/ 308");
                if (s.UsesApache)
                {
                    sb.AppendLine("\thandle /" + s.Name + "/* {");
                    AppendSite(sb, s, plan, "\t\t", pathPrefix: "/" + s.Name);
                }
                else
                {
                    sb.AppendLine("\thandle_path /" + s.Name + "/* {");
                    AppendSite(sb, s, plan, "\t\t", pathPrefix: null);
                }
                sb.AppendLine("\t}");
            }
            sb.AppendLine("\thandle {");
            sb.AppendLine("\t\troot * " + Q(IndexFolder(paths)));
            sb.AppendLine("\t\tfile_server");
            sb.AppendLine("\t}");
            sb.AppendLine("}");
            sb.AppendLine();

            // Any other name on the port (a mistyped project.localhost): the index, which lists the real ones.
            sb.AppendLine("http://:" + N(plan.WebPort) + " {");
            sb.AppendLine("\timport lumina_common");
            sb.AppendLine("\troot * " + Q(IndexFolder(paths)));
            sb.AppendLine("\trewrite * /index.html");
            sb.AppendLine("\tfile_server");
            sb.AppendLine("}");

            var demo = plan.Demo;
            var demoSite = demo == null ? null : plan.Sites.FirstOrDefault(x => x.Name == demo.Project);
            if (demoSite != null)
            {
                sb.AppendLine();
                sb.AppendLine("# Demo mode: " + demo.Project + " on the local network until LuminaDB turns it off. MariaDB is never exposed.");
                sb.AppendLine("http://:" + N(demo.Port) + " {");
                sb.AppendLine("\tbind " + demo.Address);
                sb.AppendLine("\trequest_header " + DemoHeader + " 1");
                AppendAccessLog(sb, paths, demoSite.Name, "\t");
                AppendSite(sb, demoSite, plan, "\t", pathPrefix: null);
                sb.AppendLine("}");
            }
            return sb.ToString();
        }

        private static void AppendAccessLog(StringBuilder sb, AppPaths paths, string project, string indent)
        {
            sb.AppendLine(indent + "log {");
            sb.AppendLine(indent + "\toutput file " + Q(AccessLog(paths, project)) + " {");
            sb.AppendLine(indent + "\t\troll_size 2MiB");
            sb.AppendLine(indent + "\t\troll_keep 1");
            sb.AppendLine(indent + "\t}");
            sb.AppendLine(indent + "}");
        }

        private static void AppendSite(StringBuilder sb, SiteInfo s, WebPlan plan, string i, string pathPrefix)
        {
            if (s.UsesApache)
            {
                // Apache reads the .htaccess; Caddy only passes the request on (Host header unchanged).
                sb.AppendLine(i + "reverse_proxy 127.0.0.1:" + N(plan.ApachePort) + (pathPrefix == null ? "" : " {"));
                if (pathPrefix != null)
                {
                    sb.AppendLine(i + "\theader_up X-Forwarded-Prefix " + pathPrefix);
                    sb.AppendLine(i + "}");
                }
                return;
            }
            // Never serve dotfiles (.env, .git, .user.ini) or Composer's vendor folder.
            sb.AppendLine(i + "@lumina_hidden {");
            sb.AppendLine(i + "\tpath_regexp /\\.");
            sb.AppendLine(i + "\tnot path /.well-known/*");
            sb.AppendLine(i + "}");
            sb.AppendLine(i + "respond @lumina_hidden \"Hidden by LuminaDB: files starting with a dot are private.\" 403");
            sb.AppendLine(i + "respond /vendor/* \"Hidden by LuminaDB: vendor/ holds libraries, not pages.\" 403");
            sb.AppendLine(i + "root * " + Q(s.DocumentRoot));
            sb.AppendLine(i + "php_fastcgi 127.0.0.1:" + N(plan.PhpPort) + " {");
            sb.AppendLine(i + "\tlb_try_duration 5s");
            sb.AppendLine(i + "}");
            sb.AppendLine(i + "file_server");
        }

        // ------------------------------------------------------------------ Apache

        /// <summary>
        /// httpd.conf with php-cgi through mod_proxy_fcgi. Behind Caddy it listens on an internal port and holds only
        /// the .htaccess projects; in front (no Caddy) it holds everything and listens on the web port.
        /// </summary>
        public static string BuildHttpdConf(AppPaths paths, WebStack stack, WebPlan plan)
        {
            int port = plan.ApacheInFront ? plan.WebPort : plan.ApachePort;
            var sites = plan.ApacheInFront ? plan.Sites : plan.Sites.Where(s => s.UsesApache).ToList();
            var sb = new StringBuilder();
            sb.AppendLine("# Generated by LuminaDB at every start. Don't edit: it is rewritten next time.");
            sb.AppendLine("ServerRoot " + Q(stack.ApacheDir));
            sb.AppendLine("Listen 127.0.0.1:" + N(port));
            if (plan.ApacheInFront && plan.Demo != null) sb.AppendLine("Listen " + plan.Demo.Address + ":" + N(plan.Demo.Port));
            sb.AppendLine("ServerName localhost:" + N(port));
            sb.AppendLine("ServerAdmin admin@localhost");
            foreach (var m in new[] { "mime", "dir", "authz_core", "authz_host", "alias", "rewrite", "log_config", "headers", "setenvif", "env", "proxy", "proxy_fcgi", "access_compat", "expires", "deflate" })
            {
                var so = Path.Combine(stack.ApacheDir, "modules", "mod_" + m + ".so");
                if (File.Exists(so)) sb.AppendLine("LoadModule " + m + "_module modules/mod_" + m + ".so");
            }
            sb.AppendLine("PidFile " + Q(Path.Combine(paths.Run, "httpd.pid")));
            sb.AppendLine("ErrorLog " + Q(ApacheErrorLog(paths)));
            sb.AppendLine("LogLevel warn");
            sb.AppendLine("LogFormat \"%{%Y-%m-%d %H:%M:%S}t %m \\\"%U%q\\\" %>s %D\" lumina");
            sb.AppendLine("TypesConfig conf/mime.types");
            sb.AppendLine("AddDefaultCharset UTF-8");
            sb.AppendLine("ThreadsPerChild 64");
            sb.AppendLine("MaxConnectionsPerChild 0");
            sb.AppendLine("AcceptFilter http none");
            sb.AppendLine("AcceptFilter https none");
            sb.AppendLine("EnableSendfile off");
            sb.AppendLine("EnableMMAP off");
            sb.AppendLine("LimitRequestBody 268435456");
            sb.AppendLine("ServerTokens Prod");
            sb.AppendLine("ServerSignature Off");
            sb.AppendLine("DirectoryIndex index.php index.html index.htm");
            sb.AppendLine();
            sb.AppendLine("<FilesMatch \"\\.php$\">");
            sb.AppendLine("    SetHandler \"proxy:fcgi://127.0.0.1:" + N(plan.PhpPort) + "/\"");
            sb.AppendLine("</FilesMatch>");
            sb.AppendLine("ProxyFCGISetEnvIf \"reqenv('SCRIPT_FILENAME') =~ m#^proxy:fcgi://[^/]+/([A-Za-z]:/.*)$#\" SCRIPT_FILENAME \"$1\"");
            sb.AppendLine("SetEnvIf Authorization \"(.*)\" HTTP_AUTHORIZATION=$1");
            sb.AppendLine("ProxyTimeout 300");
            sb.AppendLine();
            sb.AppendLine("<Directory />");
            sb.AppendLine("    AllowOverride None");
            sb.AppendLine("    Require all denied");
            sb.AppendLine("</Directory>");
            sb.AppendLine("<FilesMatch \"^\\.\">");
            sb.AppendLine("    Require all denied");
            sb.AppendLine("</FilesMatch>");
            sb.AppendLine("<DirectoryMatch \"[\\\\/]\\.git[\\\\/]|[\\\\/]vendor[\\\\/]\">");
            sb.AppendLine("    Require all denied");
            sb.AppendLine("</DirectoryMatch>");
            sb.AppendLine();
            foreach (var s in sites)
            {
                sb.AppendLine("<Directory " + Q(s.DocumentRoot) + ">");
                sb.AppendLine("    Options FollowSymLinks");
                sb.AppendLine("    AllowOverride All");
                sb.AppendLine("    Require all granted");
                sb.AppendLine("</Directory>");
            }
            sb.AppendLine("<Directory " + Q(IndexFolder(paths)) + ">");
            sb.AppendLine("    Require all granted");
            sb.AppendLine("</Directory>");
            bool pma = plan.ApacheInFront && plan.PhpMyAdminDir != null;
            if (pma)
            {
                sb.AppendLine("<Directory " + Q(plan.PhpMyAdminDir) + ">");
                sb.AppendLine("    AllowOverride None");
                sb.AppendLine("    Require all granted");
                sb.AppendLine("</Directory>");
                sb.AppendLine("<DirectoryMatch \"^" + Fwd(plan.PhpMyAdminDir).Replace(".", "\\.") + "/(libraries|templates|vendor|sql|setup|tmp)/\">");
                sb.AppendLine("    Require all denied");
                sb.AppendLine("</DirectoryMatch>");
            }
            sb.AppendLine();

            // The first vhost is the default: localhost, with every project also at /<name>/.
            sb.AppendLine("<VirtualHost 127.0.0.1:" + N(port) + ">");
            sb.AppendLine("    ServerName localhost");
            sb.AppendLine("    ServerAlias 127.0.0.1");
            sb.AppendLine("    RequestHeader unset " + DemoHeader);
            sb.AppendLine("    DocumentRoot " + Q(IndexFolder(paths)));
            foreach (var s in sites)
                sb.AppendLine("    Alias /" + s.Name + " " + Q(s.DocumentRoot));
            if (pma) sb.AppendLine("    RedirectMatch 302 ^/phpmyadmin http://" + PhpMyAdminConfig.Host + ".localhost:" + N(port) + "/");
            sb.AppendLine("</VirtualHost>");
            if (pma)
            {
                sb.AppendLine("<VirtualHost 127.0.0.1:" + N(port) + ">");
                sb.AppendLine("    ServerName " + PhpMyAdminConfig.Host + ".localhost");
                sb.AppendLine("    RequestHeader unset " + DemoHeader);
                sb.AppendLine("    DocumentRoot " + Q(plan.PhpMyAdminDir));
                sb.AppendLine("    <FilesMatch \"^(config\\..*|composer\\..*|package\\.json)$\">");
                sb.AppendLine("        Require all denied");
                sb.AppendLine("    </FilesMatch>");
                sb.AppendLine("</VirtualHost>");
            }
            foreach (var s in sites)
            {
                sb.AppendLine("<VirtualHost 127.0.0.1:" + N(port) + ">");
                sb.AppendLine("    ServerName " + s.Name + ".localhost");
                sb.AppendLine("    RequestHeader unset " + DemoHeader);
                sb.AppendLine("    DocumentRoot " + Q(s.DocumentRoot));
                // Behind Caddy, Caddy writes the access log; in front, Apache does.
                if (plan.ApacheInFront) sb.AppendLine("    CustomLog " + Q(AccessLog(paths, s.Name)) + " lumina");
                sb.AppendLine("</VirtualHost>");
            }
            var demoSite = plan.Demo == null ? null : sites.FirstOrDefault(x => x.Name == plan.Demo.Project);
            if (plan.ApacheInFront && demoSite != null)
            {
                sb.AppendLine("<VirtualHost " + plan.Demo.Address + ":" + N(plan.Demo.Port) + ">");
                sb.AppendLine("    ServerName " + plan.Demo.Address);
                sb.AppendLine("    RequestHeader set " + DemoHeader + " 1");
                sb.AppendLine("    DocumentRoot " + Q(demoSite.DocumentRoot));
                sb.AppendLine("    CustomLog " + Q(AccessLog(paths, demoSite.Name)) + " lumina");
                sb.AppendLine("</VirtualHost>");
            }
            return sb.ToString();
        }

