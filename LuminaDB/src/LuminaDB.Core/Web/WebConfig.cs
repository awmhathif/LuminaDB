        /// <summary>The page at http://localhost:&lt;port&gt;/ listing every project.</summary>
        public static string BuildIndexPage(WebPlan plan)
        {
            string H(string s) => WebUtility.HtmlEncode(s);
            var sb = new StringBuilder();
            sb.Append("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">");
            sb.Append("<title>LuminaDB projects</title><style>");
            sb.Append("body{margin:0;background:#F2EDE1;color:#1C1A16;font:15px/1.55 \"IBM Plex Sans\",\"Segoe UI\",sans-serif}");
            sb.Append("main{max-width:760px;margin:0 auto;padding:48px 24px}");
            sb.Append(".k{font:600 12px/1 \"IBM Plex Mono\",Consolas,monospace;letter-spacing:.08em;text-transform:uppercase;color:#625B4D;margin:0 0 8px}");
            sb.Append("h1{font:600 30px/1.2 \"Bricolage Grotesque\",\"Segoe UI\",sans-serif;margin:0 0 24px}");
            sb.Append("ul{list-style:none;margin:0;padding:0;border-top:1px solid #BDB29B}");
            sb.Append("li{border-bottom:1px solid #D8CFBC;padding:12px 0;display:flex;gap:16px;align-items:baseline;flex-wrap:wrap}");
            sb.Append("a{color:#1F3FBF;font-weight:600;text-decoration:none}a:hover{text-decoration:underline}");
            sb.Append(".alt{font:13px \"IBM Plex Mono\",Consolas,monospace;color:#625B4D}.alt a{font-weight:400;color:#4A453B}");
            sb.Append(".tag{font:600 11px/1 \"IBM Plex Mono\",Consolas,monospace;text-transform:uppercase;color:#835104}");
            sb.Append("p.e{color:#4A453B}</style></head><body><main>");
            sb.Append("<p class=\"k\">LuminaDB &middot; port ").Append(N(plan.WebPort)).Append("</p><h1>Your projects</h1>");
            if (plan.Sites.Count == 0)
            {
                sb.Append("<p class=\"e\">No projects yet. Create one in LuminaDB under Projects.</p>");
            }
            else
            {
                sb.Append("<ul>");
                foreach (var s in plan.Sites.OrderBy(x => x.Name, StringComparer.Ordinal))
                {
                    var host = "http://" + s.Name + ".localhost:" + N(plan.WebPort) + "/";
                    var path = "/" + s.Name + "/";
                    sb.Append("<li><a href=\"").Append(H(host)).Append("\">").Append(H(s.Name)).Append("</a>");
                    sb.Append("<span class=\"alt\">or <a href=\"").Append(H(path)).Append("\">localhost:").Append(N(plan.WebPort)).Append(H(path)).Append("</a></span>");
                    if (s.UsesApache) sb.Append("<span class=\"tag\">.htaccess &middot; Apache</span>");
                    sb.Append("</li>");
                }
                sb.Append("</ul>");
            }
            sb.Append("</main></body></html>");
            return sb.ToString();
        }

        public static void WriteIndex(AppPaths paths, WebPlan plan)
        {
            var dir = IndexFolder(paths);
            Directory.CreateDirectory(dir);
            File.WriteAllText(Path.Combine(dir, "index.html"), BuildIndexPage(plan), new UTF8Encoding(false));
        }
    }

    /// <summary>One line of a project's access log, from Caddy's JSON or Apache's "lumina" format.</summary>
    public sealed class AccessEntry
    {
        public DateTime When { get; set; }
        public string Method { get; set; }
        public string Uri { get; set; }
        public int Status { get; set; }
        public double Milliseconds { get; set; }

        public override string ToString() =>
            When.ToString("HH:mm:ss", CultureInfo.InvariantCulture) + "  " + Status.ToString(CultureInfo.InvariantCulture) + "  " +
            Method + " " + Uri + "  " + Milliseconds.ToString("0.#", CultureInfo.InvariantCulture) + " ms";

        private static readonly Regex CaddyRx = new Regex(
            "\"ts\":(?<ts>[0-9.e+]+).*?\"method\":\"(?<m>[A-Z]+)\".*?\"uri\":\"(?<u>(?:[^\"\\\\]|\\\\.)*)\".*?\"duration\":(?<d>[0-9.e+-]+).*?\"status\":(?<s>\\d+)",
            RegexOptions.Compiled);
        private static readonly Regex ApacheRx = new Regex(
            "^(?<t>\\d{4}-\\d\\d-\\d\\d \\d\\d:\\d\\d:\\d\\d) (?<m>[A-Z]+) \"(?<u>[^\"]*)\" (?<s>\\d{3}) (?<d>\\d+)$", RegexOptions.Compiled);

        /// <summary>Parses one log line, or returns null.</summary>
        public static AccessEntry Parse(string line)
        {
            if (string.IsNullOrWhiteSpace(line)) return null;
            var m = CaddyRx.Match(line);
            if (m.Success)
            {
                double ts = double.Parse(m.Groups["ts"].Value, CultureInfo.InvariantCulture);
                return new AccessEntry
                {
                    When = new DateTime(1970, 1, 1, 0, 0, 0, DateTimeKind.Utc).AddSeconds(ts).ToLocalTime(),
                    Method = m.Groups["m"].Value,
                    Uri = Regex.Unescape(m.Groups["u"].Value),
                    Status = int.Parse(m.Groups["s"].Value, CultureInfo.InvariantCulture),
                    Milliseconds = double.Parse(m.Groups["d"].Value, CultureInfo.InvariantCulture) * 1000,
                };
            }
            m = ApacheRx.Match(line.Trim());
            if (m.Success)
            {
                return new AccessEntry
                {
                    When = DateTime.ParseExact(m.Groups["t"].Value, "yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture),
                    Method = m.Groups["m"].Value,
                    Uri = m.Groups["u"].Value,
                    Status = int.Parse(m.Groups["s"].Value, CultureInfo.InvariantCulture),
                    Milliseconds = long.Parse(m.Groups["d"].Value, CultureInfo.InvariantCulture) / 1000.0,
                };
            }
            return null;
        }
    }
