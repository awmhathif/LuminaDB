    /// <summary>Web settings the person can change (config\web.json). Everything else is generated.</summary>
    [DataContract]
    public sealed class WebSettings
    {
        /// <summary>SPEC §8: the ten extensions verified with phpMyAdmin and the sample app.</summary>
        public static readonly string[] DefaultExtensions = { "curl", "fileinfo", "gd", "intl", "mbstring", "mysqli", "openssl", "pdo_mysql", "sodium", "zip" };

        [DataMember] public List<string> Extensions { get; set; } = DefaultExtensions.ToList();
        [DataMember] public int PreferredWebPort { get; set; } = 80;
        [DataMember] public int PreferredPhpPort { get; set; } = 9000;
        [DataMember] public int PreferredMailPort { get; set; } = 2525;
        /// <summary>Start the web server together with the database.</summary>
        [DataMember] public bool StartWithDatabase { get; set; } = true;

        public static WebSettings Load(AppPaths p)
        {
            var s = JsonFile.Read<WebSettings>(p.WebSettingsFile) ?? new WebSettings();
            if (s.Extensions == null) s.Extensions = DefaultExtensions.ToList();
            return s;
        }

        public void Save(AppPaths p) => JsonFile.Write(p.WebSettingsFile, this);
    }

    /// <summary>Everything php.ini needs that is only known at start time.</summary>
    public sealed class PhpRuntime
    {
        public int MariaDbPort { get; set; }
        public int MailPort { get; set; }
        public string TimeZone { get; set; }
    }

    /// <summary>
    /// Writes php.ini (SPEC §8): absolute extension_dir (relative paths break under Apache), only extensions whose DLL
    /// exists, display_errors off with our own error page, SMTP to the mail catcher, sessions and uploads in tmp\.
    /// </summary>
    public static class PhpConfig
    {
        public static string IniFile(AppPaths p, EngineSetKind kind) => Path.Combine(p.Config, "php-" + EngineSet.FolderName(kind) + ".ini");
        public static string PrependFile(AppPaths p) => Path.Combine(p.Config, "lumina", "prepend.php");
        public static string ErrorLog(AppPaths p) => Path.Combine(p.Logs, "php-errors.log");

        public static string Build(AppPaths paths, WebStack stack, WebSettings settings, PhpRuntime rt)
        {
            string Q(string path) => "\"" + path.Replace('\\', '/') + "\"";
            var available = new HashSet<string>(stack.AvailableExtensions, StringComparer.OrdinalIgnoreCase);
            var sb = new StringBuilder();
            sb.AppendLine("; Generated by LuminaDB at every start. Don't edit: change PHP settings per project in LuminaDB,");
            sb.AppendLine("; or add a .user.ini to the project folder. This file is rewritten next time.");
            sb.AppendLine("[PHP]");
            sb.AppendLine("engine = On");
            sb.AppendLine("short_open_tag = Off");
            sb.AppendLine("precision = 14");
            sb.AppendLine("serialize_precision = -1");
            sb.AppendLine("output_buffering = 4096");
            sb.AppendLine("implicit_flush = Off");
            sb.AppendLine("zend.enable_gc = On");
            sb.AppendLine("expose_php = Off");
            sb.AppendLine("max_execution_time = 120");
            sb.AppendLine("max_input_time = 120");
            sb.AppendLine("max_input_vars = 5000");
            sb.AppendLine("memory_limit = 256M");
            sb.AppendLine("error_reporting = E_ALL");
            sb.AppendLine("display_errors = Off");
            sb.AppendLine("display_startup_errors = Off");
            sb.AppendLine("log_errors = On");
            sb.AppendLine("html_errors = Off");
            sb.AppendLine("error_log = " + Q(ErrorLog(paths)));
            sb.AppendLine("ignore_repeated_errors = Off");
            sb.AppendLine("variables_order = \"GPCS\"");
            sb.AppendLine("request_order = \"GP\"");
            sb.AppendLine("register_argc_argv = Off");
            sb.AppendLine("auto_globals_jit = On");
            sb.AppendLine("post_max_size = 256M");
            sb.AppendLine("default_charset = \"UTF-8\"");
            sb.AppendLine("include_path = \".\"");
            sb.AppendLine("extension_dir = " + Q(stack.PhpExtDir));
            sb.AppendLine("enable_dl = Off");
            sb.AppendLine("cgi.fix_pathinfo = 1");
            sb.AppendLine("cgi.force_redirect = 0");
            sb.AppendLine("file_uploads = On");
            sb.AppendLine("upload_tmp_dir = " + Q(Path.Combine(paths.Temp, "php-uploads")));
            sb.AppendLine("upload_max_filesize = 64M");
            sb.AppendLine("max_file_uploads = 50");
            sb.AppendLine("allow_url_fopen = On");
            sb.AppendLine("allow_url_include = Off");
            sb.AppendLine("default_socket_timeout = 60");
            sb.AppendLine("auto_prepend_file = " + Q(PrependFile(paths)));
            sb.AppendLine("user_ini.filename = \".user.ini\"");
            sb.AppendLine("user_ini.cache_ttl = 5");
            sb.AppendLine("sys_temp_dir = " + Q(paths.Temp));
            sb.AppendLine();
            foreach (var ext in settings.Extensions.Distinct(StringComparer.OrdinalIgnoreCase).OrderBy(e => e, StringComparer.OrdinalIgnoreCase))
                if (available.Contains(ext)) sb.AppendLine("extension=" + ext);
            // PHP 8.5 has OPcache built in; older sets ship it as a DLL.
            bool opcacheDll = available.Contains("opcache");
            if (opcacheDll) sb.AppendLine("zend_extension=opcache");
            sb.AppendLine();
            sb.AppendLine("[opcache]");
            sb.AppendLine("opcache.enable = 1");
            sb.AppendLine("opcache.enable_cli = 0");
            sb.AppendLine("opcache.validate_timestamps = 1");
            sb.AppendLine("opcache.revalidate_freq = 0");   // edits show up on the next refresh
            sb.AppendLine();
            sb.AppendLine("[Date]");
            sb.AppendLine("date.timezone = " + (rt.TimeZone ?? "UTC"));
            sb.AppendLine();
            sb.AppendLine("[mail function]");
            sb.AppendLine("SMTP = 127.0.0.1");
            sb.AppendLine("smtp_port = " + rt.MailPort.ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("sendmail_from = \"php@lumina.localhost\"");
            sb.AppendLine("mail.add_x_header = Off");
            sb.AppendLine();
            sb.AppendLine("[Session]");
            sb.AppendLine("session.save_handler = files");
            sb.AppendLine("session.save_path = " + Q(Path.Combine(paths.Temp, "php-sessions")));
            sb.AppendLine("session.use_strict_mode = 1");
            sb.AppendLine("session.use_cookies = 1");
            sb.AppendLine("session.use_only_cookies = 1");
            sb.AppendLine("session.cookie_httponly = 1");
            sb.AppendLine("session.cookie_samesite = \"Lax\"");
            sb.AppendLine("session.gc_maxlifetime = 1440");
            sb.AppendLine();
            sb.AppendLine("[MySQLi]");
            // So new mysqli("localhost", "root", "", "db") works even when the server had to move off 3306.
            sb.AppendLine("mysqli.default_host = \"127.0.0.1\"");
            sb.AppendLine("mysqli.default_port = " + rt.MariaDbPort.ToString(CultureInfo.InvariantCulture));
            sb.AppendLine("mysqli.default_user = \"root\"");
            sb.AppendLine("mysqli.allow_persistent = On");
            return sb.ToString();
        }

        /// <summary>Writes php.ini, the error-page script and the folders PHP writes to.</summary>
        public static string Write(AppPaths paths, EngineSetKind kind, WebStack stack, WebSettings settings, PhpRuntime rt)
        {
            Directory.CreateDirectory(Path.Combine(paths.Temp, "php-uploads"));
            Directory.CreateDirectory(Path.Combine(paths.Temp, "php-sessions"));
            Directory.CreateDirectory(paths.ProjectLogs);
            Directory.CreateDirectory(Path.GetDirectoryName(PrependFile(paths)));
            File.WriteAllText(PrependFile(paths), ErrorPage.Script(paths.Projects, paths.ProjectLogs, rt.MariaDbPort), new UTF8Encoding(false));
            var file = IniFile(paths, kind);
            File.WriteAllText(file, Build(paths, stack, settings, rt), new UTF8Encoding(false));
            return file;
        }

        /// <summary>The project's .user.ini (php-cgi reads it per folder; SPEC §5.2 per-project settings).</summary>
        public static string UserIni(ProjectPhpSettings s)
        {
            var sb = new StringBuilder();
            sb.AppendLine("; PHP settings for this project, written by LuminaDB (Projects > PHP settings).");
            sb.AppendLine("; Values here apply within 5 seconds; no restart needed.");
            sb.AppendLine("upload_max_filesize = " + s.UploadMax);
            sb.AppendLine("post_max_size = " + BiggerOf(s.UploadMax, "8M"));
            sb.AppendLine("memory_limit = " + s.MemoryLimit);
            sb.AppendLine("max_execution_time = " + s.MaxExecutionSeconds.ToString(CultureInfo.InvariantCulture));
            if (!string.IsNullOrEmpty(s.TimeZone)) sb.AppendLine("date.timezone = " + s.TimeZone);
            sb.AppendLine("error_reporting = " + (s.ShowDeprecations ? "E_ALL" : "E_ALL & ~E_DEPRECATED"));
            return sb.ToString();
        }

        /// <summary>post_max_size must be at least the upload size, plus room for the other form fields.</summary>
        internal static string BiggerOf(string upload, string extra)
        {
            long Bytes(string v)
            {
                long n = long.Parse(v.Substring(0, v.Length - 1), CultureInfo.InvariantCulture);
                char u = char.ToUpperInvariant(v[v.Length - 1]);
                return u == 'G' ? n << 30 : u == 'M' ? n << 20 : n << 10;
            }
            long total = Bytes(upload) + Bytes(extra);
            return (total >> 20).ToString(CultureInfo.InvariantCulture) + "M";
        }

