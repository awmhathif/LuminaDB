        /// <summary>
        /// The PC's time zone as an IANA name for PHP's date.timezone (SPEC §5.9: PHP and MariaDB agree on the time).
        /// .NET 4.8 has no Windows → IANA conversion, so the common zones are listed; anything else falls back to a
        /// whole-hour Etc/GMT zone, or UTC.
        /// </summary>
        public static string IanaTimeZone(TimeZoneInfo tz = null)
        {
            tz = tz ?? TimeZoneInfo.Local;
            if (WindowsToIana.TryGetValue(tz.Id, out var iana)) return iana;
            var off = tz.BaseUtcOffset;
            if (off.Minutes == 0 && Math.Abs(off.Hours) <= 12)
                return off.Hours == 0 ? "UTC" : "Etc/GMT" + (off.Hours > 0 ? "-" : "+") + Math.Abs(off.Hours).ToString(CultureInfo.InvariantCulture);
            return "UTC";
        }

