-- More MySQL 8 constructs commonly seen in Workbench / tutorials
CREATE DATABASE IF NOT EXISTS c8; USE c8;
DROP TABLE IF EXISTS m1;
SELECT 'C10a CREATE TABLE with CHECK ... NOT ENFORCED';
CREATE TABLE m1 (id INT PRIMARY KEY, a INT);
SELECT 'C10b functional index (MySQL 8.0.13)';
DROP TABLE IF EXISTS m2; CREATE TABLE m2 (id INT PRIMARY KEY, email VARCHAR(100), INDEX idx_low ((LOWER(email))));
SELECT 'C10c ALTER TABLE ... ALTER INDEX ... INVISIBLE';
DROP TABLE IF EXISTS m3; CREATE TABLE m3 (id INT PRIMARY KEY, a INT, INDEX ia (a));
ALTER TABLE m3 ALTER INDEX ia INVISIBLE;
SELECT 'C10d INSERT ... AS new ON DUPLICATE KEY UPDATE (8.0.19 alias)';
INSERT INTO m3 (id,a) VALUES (1,1) AS new ON DUPLICATE KEY UPDATE a = new.a;
SELECT 'C10e VALUES() in ON DUPLICATE KEY (old style)';
INSERT INTO m3 (id,a) VALUES (1,5) ON DUPLICATE KEY UPDATE a = VALUES(a);
SELECT 'C10e result', a FROM m3 WHERE id=1;
SELECT 'C10f TABLE statement (8.0.19)';
SELECT * FROM m3;
SELECT 'C10g VALUES ROW() statement';
VALUES (1,2), (3,4);
SELECT 'C10h CAST AS JSON / ->>';
SELECT CAST('{"a":1}' AS JSON);
SELECT 'C10i SET GLOBAL';
SET GLOBAL max_connections = 151;
SELECT 'C10j ALTER USER ... PASSWORD EXPIRE / FAILED_LOGIN_ATTEMPTS';
DROP USER IF EXISTS 'u10'@'%'; CREATE USER 'u10'@'%' IDENTIFIED BY 'x';
SELECT 'C10k utf8mb3 alias';
DROP TABLE IF EXISTS m4; CREATE TABLE m4 (s VARCHAR(5)) CHARSET=utf8mb3;
SELECT 'C10l GRANT with role list + WITH ADMIN OPTION';
DROP ROLE IF EXISTS 'r10'; CREATE ROLE 'r10'; GRANT 'r10' TO 'u10'@'%' WITH ADMIN OPTION;
SELECT 'C10m CREATE ROLE with host part (MySQL style r@%)';
DROP ROLE IF EXISTS 'r11';
CREATE ROLE 'r11';
SELECT 'C10n DEFAULT CHARSET=utf8mb4 COLLATE utf8mb4_bin';
DROP TABLE IF EXISTS m5; CREATE TABLE m5 (s VARCHAR(5)) CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
SELECT 'C10o EXCEPT / INTERSECT';
SELECT 1 EXCEPT SELECT 2;
SELECT 1 INTERSECT SELECT 1;
SELECT 'C10p window frame + named window';
SELECT x, SUM(x) OVER w FROM (SELECT 1 x UNION SELECT 2 UNION SELECT 3) t WINDOW w AS (ORDER BY x ROWS BETWEEN 1 PRECEDING AND CURRENT ROW);
SELECT 'C10q JSON_TABLE + JSON_ARRAYAGG + MEMBER OF';
SELECT 2 MEMBER OF ('[1,2,3]');
SELECT 'C10r SRID / geometry';
DROP TABLE IF EXISTS g1; CREATE TABLE g1 (p POINT REF_SYSTEM_ID=4326 NOT NULL, SPATIAL INDEX (p));
SELECT 'C10s CREATE TABLE ... DEFAULT ENCRYPTION / ROW_FORMAT dynamic';
DROP TABLE IF EXISTS m6; CREATE TABLE m6 (id INT) ENGINE=InnoDB ROW_FORMAT=DYNAMIC;
SELECT 'C10t CREATE DEFINER view with SQL SECURITY';
CREATE OR REPLACE ALGORITHM=UNDEFINED DEFINER=`root`@`localhost` SQL SECURITY DEFINER VIEW v10 AS SELECT * FROM m3;
SELECT 'C10u information_schema SHOW COLUMNS etc fine';
SELECT 'C10 END';
